#!/usr/bin/env python3
"""Test inputs for tb_imu_capture.vhd.

Writes, next to this script:
    build/stim.txt        one IMU sample per line: a_x a_y a_z g_x g_y g_z (int16)
    build/fir_tb_pkg.vhd  FIR coefficients for fir_compiler_model.vhd

The stimulus mixes slow gesture-like sines, noise, full-scale steps (IIR
overshoot and output saturation) and white noise at full scale.
"""

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "filters"))
import filter_model  # noqa: E402

N = 1500
FS = 104.0


def main():
    out = HERE / "build"
    out.mkdir(exist_ok=True)
    rng = np.random.default_rng(7)
    t = np.arange(N) / FS
    x = np.zeros((N, 6))
    x[:, 0] = 6000 * np.sin(2 * np.pi * 1.3 * t) + 400 * rng.standard_normal(N)
    x[:, 1] = 9000 * np.sin(2 * np.pi * 0.7 * t + 1) + 2000 * np.sin(2 * np.pi * 14 * t)
    x[:, 2] = 8200 + 300 * rng.standard_normal(N)                     # gravity on z
    x[:, 3] = np.where((np.arange(N) // 40) % 2, 32767, -32768)       # full-scale steps
    x[:, 4] = rng.integers(-32768, 32768, N)                           # full-scale noise
    x[:, 5] = 20000 * np.sin(2 * np.pi * 3.1 * t) + 3000 * rng.standard_normal(N)
    x = np.clip(np.round(x), -32768, 32767).astype(int)
    np.savetxt(out / "stim.txt", x, fmt="%d")

    d = filter_model.load()
    h = d["fir"]["coeffs_int"]
    (out / "fir_tb_pkg.vhd").write_text(
        "-- generated by gen_tb.py from filters/filters.json\n"
        "package fir_tb_pkg is\n"
        "    type int_array is array (natural range <>) of integer;\n"
        f"    constant FIR_TB_COEFFS : int_array(0 to {len(h) - 1}) := (\n        "
        + ", ".join(str(v) for v in h)
        + ");\nend package fir_tb_pkg;\n")
    print(f"wrote {out / 'stim.txt'} ({N} samples) and {out / 'fir_tb_pkg.vhd'} ({len(h)} taps)")


if __name__ == "__main__":
    main()
